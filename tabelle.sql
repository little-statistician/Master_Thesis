CREATE TABLE IF NOT EXISTS FIRMA(
    f TEXT PRIMARY KEY NOT NULL -- !!
);

CREATE TABLE IF NOT EXISTS DOCUMENTO(
    id TEXT PRIMARY KEY NOT NULL,
    f TEXT NOT NULL,

    FOREIGN KEY(f) REFERENCES FIRMA(f)
);

CREATE TABLE IF  NOT EXISTS TEGOLA(
    t TEXT PRIMARY KEY NOT NULL
);

CREATE TABLE IF NOT EXISTS BANDA(
    b TEXT PRIMARY KEY NOT NULL -- !!
);

-- ASSOCIAZIONI

-- COMPARE(DOCUMENTO - TEGOLA)
CREATE TABLE IF NOT EXISTS COMPARE(
    id TEXT NOT NULL,
    pos INTEGER NOT NULL,
    t TEXT NOT NULL,

    PRIMARY KEY(id, pos),

    FOREIGN KEY(id) REFERENCES DOCUMENTO(id),
    FOREIGN KEY(t) REFERENCES TEGOLA(t)
);

-- PARTECIPA(FIRMA - BANDA)
CREATE TABLE IF NOT EXISTS PARTECIPA(
    f TEXT NOT NULL,
    p INTEGER NOT NULL,
    b text NOT NULL,

    PRIMARY KEY(f, p),

    FOREIGN KEY(f) REFERENCES FIRMA(f),
    FOREIGN KEY(b) REFERENCES BANDA(b)
);

-- COPPIA(DOCUMENTO - DOCUMENTO)
CREATE TABLE IF NOT EXISTS COPPIA (
    doc1 TEXT NOT NULL,
    doc2 TEXT NOT NULL,
    j DOUBLE NOT NULL,

    PRIMARY KEY (doc1, doc2),

    FOREIGN KEY (doc1) REFERENCES DOCUMENTO(id),
    FOREIGN KEY (doc2) REFERENCES DOCUMENTO(id),

    CHECK (doc1 < doc2)
);

-- indici

CREATE INDEX IF NOT EXISTS idx_partecipa_b_p_f ON PARTECIPA(b, p, f);

CREATE INDEX IF NOT EXISTS idx_coppia_j ON COPPIA(j);

CREATE INDEX IF NOT EXISTS idx_coppia_doc2 ON COPPIA(doc2); -- per la ricerca delle coppie